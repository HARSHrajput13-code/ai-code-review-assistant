def test_each_system_prompt_has_the_preamble_and_schema_within_the_cap() -> None:
    for operation, text in systems().items():
        assert PREAMBLE in text and "You never produce a score." in text
        model = AIReviewOutput if operation == "review" else AIImprovementOutput
        assert schema_text(model.model_json_schema()) in text  # D-66
        assert len(text.encode("utf-8")) <= SYSTEM_PROMPT_MAX_BYTES
    assert "WHAT TO REPORT" in systems()["review"] and "PRESERVATION" in systems()["improve"]


# --- user prompts and the untrusted-data boundary (§10.2, D-50) ----------------------------------


def block(text: str, name: str, nonce: str) -> str:
    return text.split(f"<<<{name}_{nonce}\n")[1].split(f"\n{name}_{nonce}>>>")[0]


def test_review_data_stays_inside_its_delimited_blocks() -> None:
    prompts = load_prompts("v1")
    rendered = render_review(prompts, REVIEW, "SYSTEM", "0123456789abcdef")
    user = rendered.user
    source = block(user, "SOURCE", "0123456789abcdef")
    findings = block(user, "STATIC_FINDINGS", "0123456789abcdef")
    assert source == "1 | x = '$HOME {a} ${b}'  # " + INJECTION + "\n2 | print(x)\n3 | "
    assert INJECTION in findings
    outside = user.replace(source, "").replace(findings, "")
    assert INJECTION not in outside and INJECTION not in rendered.system
    assert "(2 lines)" not in user and "(3 lines)" in user  # the line count is the source's


def test_improvement_data_stays_inside_its_delimited_blocks() -> None:
    rendered = render_improvement(load_prompts("v1"), IMPROVE, "SYSTEM", "fedcba9876543210")
    issues = block(rendered.user, "ISSUES", "fedcba9876543210")
    source = block(rendered.user, "SOURCE", "fedcba9876543210")
    assert source == SOURCE.text  # not line-numbered: the model reproduces it
    assert "print('ok')" in issues
    assert "print('ok')" not in rendered.user.replace(issues, "")


def test_rendering_is_deterministic_for_a_given_nonce() -> None:
    prompts = load_prompts("v1")
    assert render_review(prompts, REVIEW, "S", "n" * 16) == render_review(
        prompts, REVIEW, "S", "n" * 16
    )


def test_static_findings_are_capped_cut_and_ordered() -> None:
    findings = tuple(
        static_finding(n, title="t" * 150, summary="m" * 600, line=1) for n in range(30, 0, -1)
    )
    request = AIReviewRequest(language=Language.PYTHON, source=SOURCE, static_findings=findings)
    lines = static_findings_block(request).splitlines()
    assert len(lines) == 26 and lines[-1] == "(5 further findings omitted)"
    parsed = [json.loads(line) for line in lines[:-1]]
    assert [p["id"] for p in parsed] == [f"S{n}" for n in range(1, 26)]
    assert list(parsed[0]) == [
        "id",
        "line",
        "end_line",
        "severity",
        "category",
        "rule",
        "title",
        "message",
    ]
    assert (len(parsed[0]["title"]), len(parsed[0]["message"])) == (100, 200)
    # The §10.2 cuts bound each line; the JSON keys add about 10 % to the nominal 400 bytes,
    # which the request-time budget (on the actual bytes) absorbs.
    assert all(len(line.encode()) <= STATIC_FINDING_LINE_BYTES * 11 // 10 for line in lines)


def test_issues_are_capped_and_cut() -> None:
    issues = tuple(
        issue(
            Category.CORRECTNESS,
            Severity.LOW,
            Confidence.LOW,
            line=1,
            title="t" * 150,
            recommendation="r" * 800,
        )
        for _ in range(25)
    )
    request = AIImprovementRequest(language=Language.PYTHON, source=SOURCE, issues=issues)
    lines = issues_block(request).splitlines()
    assert len(lines) == PROMPT_MAX_IMPROVEMENT_ISSUES
    first = json.loads(lines[0])
    assert list(first) == [
        "id",
        "severity",
        "category",
        "title",
        "line",
        "end_line",
        "recommendation",
    ]
    assert (len(first["title"]), len(first["recommendation"])) == (100, 300)
    assert all(len(line.encode()) <= IMPROVEMENT_ISSUE_LINE_BYTES * 11 // 10 for line in lines)


def test_empty_blocks_say_none() -> None:
    empty = AIReviewRequest(language=Language.PYTHON, source=SOURCE, static_findings=())
    assert static_findings_block(empty) == "(none)"
    no_issues = AIImprovementRequest(language=Language.PYTHON, source=SOURCE, issues=())
    assert issues_block(no_issues) == "(none)"


